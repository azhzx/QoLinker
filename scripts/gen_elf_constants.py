#!/usr/bin/env python3
"""One-shot code generator: emits MoonBit ELF constant tables from LLVM headers.

Source of truth (llvm-project):
  llvm/include/llvm/BinaryFormat/ELF.h          (ELF_*/enum constants)
  llvm/include/llvm/BinaryFormat/ELF.def        (EM_* machine codes)
  llvm/include/llvm/BinaryFormat/ELFRelocs/X86_64.def  (R_X86_64_* codes)

Usage:
  python3 scripts/gen_elf_constants.py <llvm-include-dir> > elfspec/elf_constants.mbt

Regenerate only when syncing with a newer lld. Values are emitted as MoonBit
`Int` (32-bit); constants >= 0x80000000 are skipped with a comment.
"""
import re
import sys

PREFIX_WHITELIST = (
    "ET_",
    "EM_",
    "SHT_",
    "SHF_",
    "SHN_",
    "STB_",
    "STT_",
    "STV_",
    "PT_",
    "PF_",
    "DT_",
    "DF_",
    "NT_",
    "GRP_",
    "VER_",
    "ELFCLASS",
    "ELFDATA",
    "EV_",
)

# These SHF_/PT_ masks fit only in unsigned space or are unused by the linker;
# skipping keeps every generated constant a positive Int (32-bit).
SKIP_NAMES = {
    "SHF_MASKOS",
    "SHF_MASKPROC",
    "PT_MASK",
    "DT_ENCODING",
    "DF_MASKOS",
    "DF_MASKPROC",
}


def parse_elf_h(path: str):
    consts = {}
    text = open(path, encoding="utf-8").read()
    # Enum entries of the form `  NAME = value,` inside `enum { ... }`.
    for m in re.finditer(r"^\s{2}([A-Z][A-Z0-9_]*)\s*=\s*(0[xX][0-9a-fA-F]+|\d+)[uUlL]*\s*,?\s*(?://.*)?$", text, re.M):
        name, value = m.group(1), int(m.group(2), 0)
        if any(name.startswith(p) for p in PREFIX_WHITELIST) and name not in SKIP_NAMES:
            if name in consts and consts[name] != value:
                sys.exit(f"conflicting definition for {name}: {consts[name]} vs {value}")
            consts[name] = value
    return consts


def parse_elf_def(path: str):
    consts = {}
    for m in re.finditer(r"ELF_MACHINE\((EM_[A-Za-z0-9_]+),\s*(\d+)", open(path, encoding="utf-8").read()):
        consts[m.group(1)] = int(m.group(2))
    return consts



def parse_dynamic_tags(path: str):
    consts = {}
    text = open(path, encoding="utf-8").read()
    for m in re.finditer(r"DYNAMIC_TAG\(([A-Za-z0-9_]+),\s*(0[xX][0-9a-fA-F]+|\d+)\)", text):
        consts["DT_" + m.group(1)] = int(m.group(2), 0)
    return consts

def parse_reloc_def(path: str):
    consts = {}
    for m in re.finditer(r"ELF_RELOC\(([A-Za-z0-9_]+),\s*(\d+)\)", open(path, encoding="utf-8").read()):
        consts[m.group(1)] = int(m.group(2))
    return consts


def emit(consts):
    skipped = [(n, v) for n, v in consts.items() if v >= 0x80000000]
    out = []
    out.append("// Generated by scripts/gen_elf_constants.py from LLVM's BinaryFormat/ELF.h,")
    out.append("// ELF.def and ELFRelocs/X86_64.def. Do not edit by hand.")
    out.append("")
    out.append("///|")
    for name, value in sorted(consts.items()):
        if value < 0x80000000:
            out.append(f"pub const {name} : Int = {value}")
    if skipped:
        out.append("")
        out.append("// Skipped (needs > 32-bit unsigned space):")
        for name, value in sorted(skipped):
            out.append(f"// {name} = 0x{value:x}")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    base = sys.argv[1]
    consts = {}
    consts.update(parse_elf_h(f"{base}/llvm/BinaryFormat/ELF.h"))
    consts.update(parse_elf_def(f"{base}/llvm/BinaryFormat/ELF.def"))
    consts.update(parse_reloc_def(f"{base}/llvm/BinaryFormat/ELFRelocs/X86_64.def"))
    consts.update(parse_dynamic_tags(f"{base}/llvm/BinaryFormat/DynamicTags.def"))
    sys.stdout.write(emit(consts))


if __name__ == "__main__":
    main()
